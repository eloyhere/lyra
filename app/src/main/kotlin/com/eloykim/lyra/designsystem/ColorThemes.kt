/**
 * 内置配色方案。
 *
 * 每种主题都从同一个 seed 颜色按 Material 3 tonal-spot 规则展开：
 * primary chroma 48、secondary 16、tertiary 24、neutral 6、neutralVariant 8
 * （青瓷为了压住荧光感略微降低饱和），再把色阶映射到标准的
 * colorPrimary / colorOnPrimary / colorSurfaceContainer 等角色上，
 * 所以可以整体替换 [ColorScheme] 而不用改任何 UI 代码。
 *
 * 深色模式的色阶（80/20/30/90、surface tone 6…）与浅色模式的容器色阶
 * 都按 Material 3 规范取值；色值由 Material Color Utilities 生成。
 */
enum class LyraColorTheme(
    val id: String,
    /** 生成该配色的种子色，仅用于文档与预览。 */
    val seed: Long,
) {
    /** 默认主题。深靛紫，像夜空里的星等；比 Material 基线紫更冷、更深，浅色下主色更沉稳，深色下仍保持足够亮度。
     *
     * seed = 0xFF4A44A8
     */
    Lyra("lyra", 0xFF4A44A8),

    /** 海盐蓝。取自晴天海面的标准蓝，适合长时间阅读。
     *
     * seed = 0xFF0061A4
     */
    Ocean("ocean", 0xFF0061A4),

    /** 青瓷。降低饱和度的青绿，避免高饱和青色在浅色容器里发荧光。
     *
     * seed = 0xFF006A6A
     */
    Teal("teal", 0xFF006A6A),

    /** 森林绿。低明度绿主色配浅绿容器，安定、耐看。
     *
     * seed = 0xFF386A20
     */
    Forest("forest", 0xFF386A20),

    /** 琥珀金。黄棕主色，深色模式下的亮金色非常醒目。
     *
     * seed = 0xFF7D5700
     */
    Amber("amber", 0xFF7D5700),

    /** 落日橙。砖红主色，适合作为强调任务的暖色主题。
     *
     * seed = 0xFFB02F00
     */
    Sunset("sunset", 0xFFB02F00),

    /** 玫瑰。莓红主色配粉色容器，柔和但不寡淡。
     *
     * seed = 0xFF984061
     */
    Rose("rose", 0xFF984061),

    /** 石墨。完全去饱和的单色主题，适合配色敏感或需要极简的场景。
     *
     * seed = 0xFF4F4F52
     */
    Graphite("graphite", 0xFF4F4F52),
    ;

    /** 返回该主题在浅色 / 深色下的完整配色。 */
    fun colorScheme(darkTheme: Boolean): ColorScheme =
        if (darkTheme) darkScheme else lightScheme

    private val lightScheme: ColorScheme
        get() = when (this) {
            Lyra -> LyraLightScheme
            Ocean -> OceanLightScheme
            Teal -> TealLightScheme
            Forest -> ForestLightScheme
            Amber -> AmberLightScheme
            Sunset -> SunsetLightScheme
            Rose -> RoseLightScheme
            Graphite -> GraphiteLightScheme
        }

    private val darkScheme: ColorScheme
        get() = when (this) {
            Lyra -> LyraDarkScheme
            Ocean -> OceanDarkScheme
            Teal -> TealDarkScheme
            Forest -> ForestDarkScheme
            Amber -> AmberDarkScheme
            Sunset -> SunsetDarkScheme
            Rose -> RoseDarkScheme
            Graphite -> GraphiteDarkScheme
        }

    companion object {
        /** 未显式选择时的默认主题。 */
        val Default: LyraColorTheme = Lyra

        /** 旧版本或损坏的偏好值回退到默认主题，不抛异常。 */
        fun byId(id: String?): LyraColorTheme =
            entries.firstOrNull { it.id == id } ?: Default
    }
}

