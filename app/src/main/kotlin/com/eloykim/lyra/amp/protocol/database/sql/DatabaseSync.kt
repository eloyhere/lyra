package com.eloykim.lyra.amp.protocol.database.sql

import java.math.BigInteger
import java.sql.Connection
import java.sql.DriverManager
import java.sql.PreparedStatement
import java.sql.ResultSet
import java.sql.Types

/**
 * Narrow port of the `node:sqlite` surface the reference database layer uses
 * (port of `src/database/sql/sql.ts`, `src/database/store/database.ts` and the
 * code that imports `DatabaseSync`).
 *
 * The reference opens a real SQLite file with `new DatabaseSync(path)`. Kotlin /
 * Android cannot rely on `node:sqlite`; Android 29 exposes SQLite only through
 * `android.database.sqlite`. So this package stops at a three-method port —
 * `exec`, `prepare`, `close` — and supplies a `java.sql` adapter
 * ([JdbcDatabaseSync]) that a host can point at any JDBC driver.
 *
 * ## Binding seams
 *
 * - `node:sqlite` rows are plain JavaScript objects typed by the caller. Here a
 *   row is a [Row] (a labelled, insertion-ordered map) and every `Sql` instance
 *   carries a `(Row) -> TEntity` mapper. This is the one place where the port
 *   must name a mapping function the reference did not need.
 * - `StatementSync.run(...)` takes JavaScript values; this port normalizes them
 *   through [toSqlParameter] exactly like the reference's public `run`, so a
 *   wrong value fails before touching the driver.
 * - `lastInsertRowid` is a JavaScript `number | bigint`; here it is a [Long].
 *   Repositories use [MutationResult.insertedId] where the reference writes
 *   `Number(result.lastInsertRowid)`.
 */

/** Value accepted by a SQLite bound parameter (`src/database/sql/sql.ts`). */
sealed interface SqlParameter {

    /** SQLite TEXT. */
    data class Text(val value: String) : SqlParameter

    /** SQLite INTEGER, covering JavaScript `number` integers and `bigint`. */
    data class Integral(val value: Long) : SqlParameter

    /** SQLite REAL, covering JavaScript non-integer `number`. */
    data class Real(val value: Double) : SqlParameter

    /** SQLite BLOB, covering `Uint8Array`. */
    data class Blob(val value: ByteArray) : SqlParameter

    /** SQL NULL, covering `null` and `undefined`. */
    data object Null : SqlParameter
}

/**
 * Result of an INSERT, UPDATE or DELETE (`MutationResult` in the reference).
 */
data class MutationResult(
    /** Number of rows changed by the statement. */
    val changes: Int,
    /** Rowid generated by an INSERT, or zero when none was generated. */
    val lastInsertRowid: Long = 0L,
) {
    /** The `Number(lastInsertRowid)` projection the repositories use. */
    val insertedId: Int get() = lastInsertRowid.toInt()
}

/**
 * Convert a Kotlin value into a value the port can bind.
 *
 * Booleans become `1`/`0`, `null` becomes NULL, and unsupported object types
 * fail early instead of being stringified silently. Matches
 * `toSqlParameter` in the reference, with the two JavaScript-specific cases
 * documented below.
 *
 * @throws IllegalArgumentException when the value has no SQLite representation.
 */
fun toSqlParameter(value: Any?): SqlParameter {
    if (value == null) {
        return SqlParameter.Null
    }
    if (value is SqlParameter) {
        return value
    }
    if (value is Boolean) {
        return SqlParameter.Integral(if (value) 1L else 0L)
    }
    if (value is String) {
        return SqlParameter.Text(value)
    }
    if (value is Long || value is Int || value is Short || value is Byte) {
        return SqlParameter.Integral((value as Number).toLong())
    }
    if (value is BigInteger) {
        // JavaScript `bigint` binds unchanged; SQLite integers are signed 64-bit.
        if (value.bitLength() >= 64) {
            throw IllegalArgumentException("SQL parameters cannot exceed the signed 64-bit range")
        }
        return SqlParameter.Integral(value.toLong())
    }
    if (value is Float || value is Double) {
        val number = (value as Number).toDouble()
        if (!number.isFinite()) {
            throw IllegalArgumentException("SQL parameters cannot be NaN or Infinity")
        }
        return SqlParameter.Real(number)
    }
    if (value is ByteArray) {
        return SqlParameter.Blob(value)
    }
    throw IllegalArgumentException("Unsupported SQL parameter type: ${value::class.java.name}")
}

/**
 * Validate a SQL identifier before it is interpolated into a statement.
 *
 * @return the identifier unchanged.
 * @throws IllegalArgumentException when it is not `[A-Za-z_][A-Za-z0-9_]*`.
 */
fun assertSqlIdentifier(identifier: String): String {
    if (!SQL_IDENTIFIER.matches(identifier)) {
        throw IllegalArgumentException("Invalid SQL identifier: $identifier")
    }
    return identifier
}

private val SQL_IDENTIFIER = Regex("^[A-Za-z_][A-Za-z0-9_]*$")

/**
 * One result row: a label-to-value map in column order.
 *
 * SQLite is dynamically typed, so the typed getters accept any [Number] and
 * return null for a SQL NULL or for a value of an unexpected class. The
 * reference reads plain JavaScript properties and would produce `undefined`
 * instead; both fail closed in the same places.
 */
class Row(private val values: Map<String, Any?>) {

    val columnNames: Set<String> get() = values.keys

    fun has(name: String): Boolean = values.containsKey(name)

    fun raw(name: String): Any? = values[name]

    fun string(name: String): String? = values[name] as? String

    fun int(name: String): Int? = (values[name] as? Number)?.toInt()

    fun long(name: String): Long? = (values[name] as? Number)?.toLong()

    fun double(name: String): Double? = (values[name] as? Number)?.toDouble()

    /** SQLite booleans are `0`/`1`; a driver may also return a [Boolean]. */
    fun boolean(name: String): Boolean? = when (val value = values[name]) {
        is Boolean -> value
        is Number -> value.toLong() != 0L
        else -> null
    }

    fun requireString(name: String): String =
        string(name) ?: throw IllegalStateException("column $name is not a text value")

    fun requireInt(name: String): Int =
        int(name) ?: throw IllegalStateException("column $name is not an integer value")

    fun requireLong(name: String): Long =
        long(name) ?: throw IllegalStateException("column $name is not an integer value")

    fun requireDouble(name: String): Double =
        double(name) ?: throw IllegalStateException("column $name is not a numeric value")

    fun asMap(): Map<String, Any?> = LinkedHashMap(values)

    override fun toString(): String = values.toString()

    companion object {
        /** Build a row from ordered column/value pairs, keeping declaration order. */
        fun of(vararg pairs: Pair<String, Any?>): Row {
            val map = LinkedHashMap<String, Any?>(pairs.size)
            pairs.forEach { (key, value) -> map[key] = value }
            return Row(map)
        }
    }
}

/**
 * A prepared statement. Mirrors the three `StatementSync` entry points used by
 * the reference database layer: `run`, `all`, `get`.
 */
interface Statement {

    fun run(vararg params: SqlParameter): MutationResult

    fun all(vararg params: SqlParameter): List<Row>

    fun get(vararg params: SqlParameter): Row?
}

/**
 * An open connection. The only seam between this module and a concrete SQLite
 * implementation.
 */
interface DatabaseSync {

    fun exec(sql: String)

    fun prepare(sql: String): Statement

    fun close()
}

/** Opens a [DatabaseSync] for a path (`":memory:"` in tests and demos). */
fun interface DatabaseOpener {
    fun open(path: String): DatabaseSync
}

/**
 * `java.sql` adapter for hosts that have a JDBC driver.
 *
 * Android 29 ships `java.sql` but no JDBC SQLite driver, so the Android host is
 * expected to install its own [DatabaseOpener] over `android.database.sqlite`.
 * This class is the reference adapter for desktop/test hosts.
 *
 * `lastInsertRowid` comes from `getGeneratedKeys()` when the driver supports it;
 * an INSERT on a driver that does not is followed by
 * `SELECT last_insert_rowid()` on the same connection.
 */
class JdbcDatabaseSync(private val connection: Connection) : DatabaseSync {

    override fun exec(sql: String) {
        connection.createStatement().use { statement -> statement.execute(sql) }
    }

    override fun prepare(sql: String): Statement = JdbcStatement(connection, sql)

    override fun close() {
        connection.close()
    }

    companion object {

        /** Open a JDBC URL directly, e.g. `jdbc:sqlite:/tmp/amp.db`. */
        fun open(url: String): JdbcDatabaseSync = JdbcDatabaseSync(DriverManager.getConnection(url))

        /** Build a [DatabaseOpener] that maps a store path to a JDBC URL. */
        fun opener(url: (String) -> String): DatabaseOpener =
            DatabaseOpener { path -> open(url(path)) }
    }
}

private class JdbcStatement(
    private val connection: Connection,
    private val sql: String,
) : Statement {

    override fun run(vararg params: SqlParameter): MutationResult {
        connection.prepareStatement(sql).use { statement ->
            bind(statement, params)
            val changes = statement.executeUpdate()
            var rowid = 0L
            try {
                statement.generatedKeys?.use { keys -> if (keys.next()) rowid = keys.getLong(1) }
            } catch (_: Exception) {
                // The driver does not expose generated keys; fall back to the scalar.
            }
            if (rowid == 0L && sql.trimStart().startsWith("INSERT", ignoreCase = true)) {
                connection.createStatement().use { probe ->
                    probe.executeQuery("SELECT last_insert_rowid()").use { result ->
                        if (result.next()) rowid = result.getLong(1)
                    }
                }
            }
            return MutationResult(changes = changes, lastInsertRowid = rowid)
        }
    }

    override fun all(vararg params: SqlParameter): List<Row> {
        connection.prepareStatement(sql).use { statement ->
            bind(statement, params)
            statement.executeQuery().use { result -> return readAll(result) }
        }
    }

    override fun get(vararg params: SqlParameter): Row? {
        connection.prepareStatement(sql).use { statement ->
            bind(statement, params)
            statement.executeQuery().use { result -> return readOne(result) }
        }
    }

    private fun bind(statement: PreparedStatement, params: Array<out SqlParameter>) {
        params.forEachIndexed { index, param ->
            val position = index + 1
            when (param) {
                is SqlParameter.Null -> statement.setNull(position, Types.NULL)
                is SqlParameter.Text -> statement.setString(position, param.value)
                is SqlParameter.Integral -> statement.setLong(position, param.value)
                is SqlParameter.Real -> statement.setDouble(position, param.value)
                is SqlParameter.Blob -> statement.setBytes(position, param.value)
            }
        }
    }

    private fun readAll(result: ResultSet): List<Row> {
        val metadata = result.metaData
        val labels = (1..metadata.columnCount).map { metadata.getColumnLabel(it) }
        val rows = ArrayList<Row>()
        while (result.next()) {
            val values = LinkedHashMap<String, Any?>(labels.size)
            labels.forEachIndexed { index, label -> values[label] = result.getObject(index + 1) }
            rows += Row(values)
        }
        return rows
    }

    private fun readOne(result: ResultSet): Row? {
        if (!result.next()) {
            return null
        }
        val metadata = result.metaData
        val values = LinkedHashMap<String, Any?>(metadata.columnCount)
        for (index in 1..metadata.columnCount) {
            values[metadata.getColumnLabel(index)] = result.getObject(index)
        }
        return Row(values)
    }
}
